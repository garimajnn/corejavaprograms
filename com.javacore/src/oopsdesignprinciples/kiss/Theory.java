package oopsdesignprinciples.kiss;

public class Theory {

/**
 * Kiss Principle means keep it simple stupid !!
 * 1. I should always keep my code as simple as possible
 * 2. By keeping solution simple,developers can improve their own prouductivity
 * while ensuring that their code remains accessible to others.
 * 3.“While KISS promotes simplicity, overusing it can reduce flexibility
 * and lead to under-engineering if future requirements or complexity are ignored.”
 *
 * */

// Mainly it is used in DSA problems



/**
 * Steps to Implement KISS PRINCIPLE
 * 1. BREAK DOWN PROBLEMS - BREAK BIG PROBLEM TO SMALL SMALL MANAGEABLE PART,THIS REDUCE COMPLEXITY,MAKE
 * COMPONENTS EASIER TO UNDERSTAND.
 * 2.USE CLEAR NAMING CONVENTION
 * 3.WISELY FOLLOW DESIGN PATTERNS LIKE FACTORY,SINGLETON,STRATEGY TO UNDERSTAND THE SOLUTIO
 * 4.BREAK THE CODE FOR SINGLE PURPOSE FUNCTION OR MODULE . THIS ADHERS TO THE SINGLE RESPONSIBILITY PRINCIPLE.
 * */


/**
 * Advantage
 * 1. keep code clean.
 * 2. make developement easy.
 * 3. easy for debug.
 * 4. reduce maintenance cost.
 *
 * */

/**
 * Disadvantage
 * 1. Limited flexibility - keeping things simple may result in design that cannot accomodate
 * future changes or scalability.
 * 2. Sometimes developers misinterpret simplicity - they think minimal lines of code over clarity,
 * results in bad design
 * 3. Sometime oversimplifying ignore the edge case , or long term requirement
 *
 *
 * */

}

